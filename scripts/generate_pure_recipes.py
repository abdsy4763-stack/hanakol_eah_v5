    nl = name.lower()
    
    # Spices & seasonings
    if any(k in nl for k in ["ملح", "فلفل", "بهار", "قرفة", "هيل", "كمون", "كزبرة يابسة", "كركم", "كاري", "نعناع يابس", "نعناع مجفف", "سماق", "مستكة", "محلب", "خميرة", "بيكنج", "كربونات", "فانيليا", "دقة"]):
        return {"amount": 1, "unit": "ملعقة صغيرة", "item": name}
    if "زعفران" in nl:
        return {"amount": 0.5, "unit": "ملعقة صغيرة", "item": name}
        
    # Sugar & sweeteners
    if "سكر" in nl:
        return {"amount": 1.5, "unit": "كوب", "item": name}
    if "قطر" in nl:
        return {"amount": 2, "unit": "كوب", "item": name}
    if any(k in nl for k in ["ماء زهر", "ماء ورد", "خل"]):
        return {"amount": 2, "unit": "ملعقة كبيرة", "item": name}
        
    # Liquids / fats / oils / pastes
    if any(k in nl for k in ["سمن", "زبدة", "طحينة", "دبس رمان", "دبس فليفلة", "معجون طماطم", "صلصة"]):
        return {"amount": 2, "unit": "ملعقة كبيرة", "item": name}
    if any(k in nl for k in ["زيت زيتون", "عصير ليمون", "عصير نارنج", "تمر هندي"]):
        return {"amount": 4, "unit": "ملعقة كبيرة", "item": name}
    if any(k in nl for k in ["زيت نباتي", "زيت للقلي", "زيت غزير"]):
        return {"amount": 2, "unit": "كوب", "item": name}
        
    # Dairy
    if any(k in nl for k in ["لبن زبادي", "لبن رائب", "زبادي", "لبن غنم"]):
        return {"amount": 1.2, "unit": "كغ", "item": name}
    if any(k in nl for k in ["حليب", "ماء", "مرق"]):
        return {"amount": 3, "unit": "كوب", "item": name}
    if any(k in nl for k in ["قشطة", "قيمر", "جبنة", "جبن"]):
        return {"amount": 250, "unit": "غرام", "item": name}
        
    # Starches & thickeners
    if "نشا" in nl:
        return {"amount": 3, "unit": "ملعقة كبيرة", "item": name}
        
    # Nuts
    if any(k in nl for k in ["صنوبر", "لوز", "جوز", "فستق", "كاجو"]):
        return {"amount": 50, "unit": "غرام", "item": name}
        
