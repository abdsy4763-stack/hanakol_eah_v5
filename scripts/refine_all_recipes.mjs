// Helper to determine dish profile
function getDishProfile(r) {
  const t = r.title;
  const c = r.category;

  // 1. Seafood / Fish
  const fishWords = [
    'سمك', 'سردين', 'روبيان', 'قريدس', 'جمبري', 'حبار', 'سلمون', 'صيادية',
    'دنيس', 'زبيدي', 'هامور', 'كنعد', 'تونة', 'طون', 'أخطبوط', 'سي فود',
    'سلطعون', 'كابوريا', 'محار', 'كلماري', 'كالاماري', 'فواكه البحر', 'سيبيا',
    'بلطي', 'ماكريل', 'فروخ', 'سنغر', 'سلطان إبراهيم', 'لقز', 'بوري', 'فونغولي'
  ];
  if (fishWords.some(w => t.includes(w))) return 'seafood';

  // 2. Sweets / Desserts / Drinks
  if (c === 'حلويات ومشروبات' || [
    'كنافة', 'معمول', 'بقلاوة', 'كيك', 'بسبوسة', 'قطايف', 'برازق', 'غريبة',
    'مهلبية', 'هريسة', 'رز بحليب', 'أم علي', 'بلح الشام', 'عوامة', 'لقيمات',
    'مشبك', 'تارت', 'حلاوة الجبن', 'تمرية', 'بين نارين', 'مفروكة', 'كليجة',
    'زنود الست', 'دانغو', 'دوراياكي', 'موتشي', 'براوني', 'تيراميسو', 'تشيز كيك',
    'بانا كوتا', 'كريم كراميل', 'سفوف', 'عصيدة', 'زلابية', 'غريبة'
  ].some(w => t.includes(w))) {
    if (['شاي', 'قهوة', 'سحلب', 'كركديه', 'تمر هندي', 'عصير', 'شراب', 'مشروب', 'ماتشا', 'سموذي', 'كوكتيل'].some(w => t.includes(w))) {
      return 'drink';
    }
    return 'dessert';
  }

  // 3. Salads / Cold appetizers
  if (c === 'مقبلات وسلطات') {
    if (['سلطة', 'فتوش', 'تبولة', 'متبل', 'بابا غنوج', 'سيزر', 'كولسلو', 'سلطه', 'سلطة خضراء', 'جرجير'].some(w => t.includes(w))) return 'salad';
    if (['حمص', 'لبنة', 'مسبحة', 'جبنة', 'زيتون', 'يالنجي', 'مقدوس'].some(w => t.includes(w))) return 'cold_appetizer';
    if (['كبة', 'سمبوسك', 'فطائر', 'برك'].some(w => t.includes(w))) return 'hot_appetizer';
    return 'salad';
  }

  // 4. Soups
  if (c === 'شوربات' || t.includes('شوربة') || t.includes('حساء') || t.includes('حريرة') || t.includes('كشك')) {
    return 'soup';
  }

  // 5. Pastries / Breads
  if (c === 'معجنات ومخبوزات' || [
    'مناقيش', 'فطائر', 'بيتزا', 'صفيحة', 'بوراك', 'سمبوسك', 'كرواسون', 'خبز',
    'فوكاشيا', 'فطيرة', 'منقوشة', 'لحم بعجين', 'عيش', 'رغيف', 'توست'
  ].some(w => t.includes(w))) {
    return 'pastry';
  }

  // 6. Breakfast / Eggs
  if (c === 'فطور وعشاء') {
    if (['بيض', 'شكشوكة', 'عجة', 'أومليت', 'مفركة بيض', 'عيون'].some(w => t.includes(w))) return 'breakfast_egg';
    if (['فول', 'فلافل', 'فتة', 'حمص', 'لبنة'].some(w => t.includes(w))) return 'breakfast_legume';
    return 'breakfast_general';
  }

  // 7. Stuffed / Vine Leaves / Mahshi
  if (['محشي', 'يبرق', 'ورق عنب', 'دولمة', 'ملفوف', 'شيخ المحشي باذنجان', 'شيش برك'].some(w => t.includes(w)) && !t.includes('لبن')) {
    return 'mahshi';
  }

  // 8. Yogurt dishes (لبن)
  if (['شاكرية', 'كبة لبنية', 'باشا وعساكره', 'لبنية', 'شيخ المحشي كوسا باللبن', 'شيخ المحشي باللبن'].some(w => t.includes(w))) {
    return 'yogurt_dish';
  }

  // 9. Rice / Biryani / Mandi / Kabsa / Mansaf
  if (['كبسة', 'برياني', 'مندي', 'مجبوس', 'أوزي', 'منسف', 'بخاري', 'مقلوبة', 'مدفون', 'بايلا', 'ريزوتو', 'أرز', 'رز', 'زرب'].some(w => t.includes(w))) {
    return 'rice_dish';
  }

  // 10. Pasta / Noodles
  if (['معكرونة', 'سباغيتي', 'باستا', 'لازانيا', 'نودلز', 'باد تاي', 'بيني', 'فيتوتشيني', 'رافيولي'].some(w => t.includes(w))) {
    return 'pasta';
  }

  // 11. Chicken
  if (['دجاج', 'فراخ', 'شيش طاووق', 'كوردون بلو', 'تندر', 'بروستد', 'مسحب', 'شاورما دجاج'].some(w => t.includes(w))) {
    return 'chicken';
  }

  // 12. Vegetarian stews / Veggies
  if (['خضار', 'سبانخ', 'ملوخية', 'بامية', 'فاصولياء', 'لوبياء', 'عدس', 'مجدرة', 'مسقعة', 'مفركة بطاطا', 'هندبة', 'كوسا', 'مجلجلة'].some(w => t.includes(w)) &&
      !t.includes('لحم') && !t.includes('دجاج') && !t.includes('موزات') && !t.includes('كفتة') && !t.includes('غنم') && !t.includes('عجل')) {
    return 'vegetarian_stew';
  }

  // 13. Meat dishes
  return 'meat_main';
}

