    if (!hasFish) {
      let fName = 'سمك بحري طازج منظف';
      if (t.includes('روبيان') || t.includes('جمبري')) fName = 'روبيان طازج منظف ومقشر';
      else if (t.includes('حبار') || t.includes('كالاماري')) fName = 'حبار طازج مقطع حلقات';
      else if (t.includes('سردين')) fName = 'سردين بلدي طازج منظف';
      else if (t.includes('سلمون')) fName = 'فيليه سلمون طازج';
      else if (t.includes('هامور')) fName = 'سمك هامور بحري طازج';
      ings.unshift({ amount: 750, unit: 'غرام', item: fName });
    }

