function getExactDishType(r) {
  const t = r.title;
  const c = r.category;

  // Specific famous dishes first
  if (t.includes('حراق أصبعو')) return 'harraq_esbaoo';
  if (t.includes('يالنجي')) return 'yalangi';
  if (t.includes('كبة أرنبية')) return 'kibbeh_arnabiyeh';
  if (t.includes('تيراميسو')) return 'tiramisu';
  if (t.includes('ماتشا') && t.includes('آيس كريم')) return 'matcha_icecream';
  if (t.includes('بيض شاي مسلوق')) return 'chinese_tea_eggs';
  if (t.includes('هندبة')) return 'hindbeh';
  if (t.includes('مسخن')) return 'musakhan';
  if (t.includes('مقلوبة')) return 'maqluba';
  if (t.includes('مسقعة')) return 'moussaka';
  if (t.includes('أوزي')) return 'ouzi';
  if (t.includes('قدرة خليلية') || t.includes('قدرة')) return 'qidreh';
  if (t.includes('مفتول')) return 'maftool';
  if (t.includes('حواوشي')) return 'hawawshi';
  if (t.includes('لازانيا')) return 'lasagna';
  if (t.includes('كشري')) return 'koshari';
  if (t.includes('ملوخية')) return 'molokhia';
  if (t.includes('منسف')) return 'mansaf';
  if (t.includes('فلافل')) return 'falafel';
  if (t.includes('فول مدمس') || t.includes('فول بالزيت') || t.includes('فول بالخلطة')) return 'foul';
  if ((t.startsWith('فتة') || t.includes(' فتة') || t.includes('الفتة')) && !t.includes('كفتة') && !t.includes('فتوش')) return 'fatteh';
  if (t.includes('شاورما')) return 'shawarma';

  // 1. Seafood / Fish (Checked BEFORE generic couscous, kofta, etc.)
  if (t.includes('صلصة المحار') && (t.includes('لحم') || t.includes('دجاج') || t.includes('بروكلي'))) {
    return 'stir_fry_meat';
  }

  const fishWords = [
    'سمك', 'سردين', 'روبيان', 'قريدس', 'جمبري', 'حبار', 'سلمون', 'صيادية',
    'دنيس', 'زبيدي', 'هامور', 'كنعد', 'تونة', 'طون', 'أخطبوط', 'سي فود',
    'سلطعون', 'كابوريا', 'محار', 'كلماري', 'كالاماري', 'فواكه البحر', 'سيبيا',
    'بلطي', 'ماكريل', 'فروخ', 'سنغر', 'سلطان إبراهيم', 'لقز', 'بوري', 'فونغولي'
  ];
  if (fishWords.some(w => t.includes(w))) {
    if (t.includes('مسكوف')) return 'seafood_masgouf';
    if ((t.includes('روبيان') || t.includes('جمبري')) && (t.includes('طاجن') || t.includes('صلصة'))) return 'seafood_shrimp_tajin';
    if (t.includes('كفتة')) return 'seafood_kofta';
    if (t.includes('كسكس')) return 'seafood_couscous';
    if (t.includes('صيادية')) return 'seafood_sayadieh';
    if (t.includes('ريزوتو') || t.includes('بايلا')) return 'seafood_rice';
    if (t.includes('باستا') || t.includes('سباغيتي') || t.includes('فونغولي') || t.includes('نودلز') || t.includes('باد تاي')) return 'seafood_pasta';
    if (t.includes('شوربة') || t.includes('حساء')) return 'seafood_soup';
    if (t.includes('مشوي') || t.includes('فرن') || t.includes('سنجاري') || t.includes('مسكوف') || t.includes('طاجن') || t.includes('صينية')) return 'seafood_baked_grilled';
    if (t.includes('مقلي') || t.includes('سنغر') || t.includes('سلطان إبراهيم') || t.includes('كالاماري')) return 'seafood_fried';
    return 'seafood_general';
  }

  // Couscous (meat/chicken/veg)
  if (t.includes('كسكس')) return 'couscous';

  // 2. Drinks (Verify genuine drink)
  const isActualDrink = ['شاي بالنعناع', 'شاي كرك', 'قهوة تركية', 'قهوة عربية', 'سحلب', 'كركديه بارد', 'عصير رمان', 'شراب التمر هندي', 'سموذي', 'ماتشا لاتيه', 'بونا قهوة', 'سوجونغوا'].some(w => t.includes(w)) ||
    (c === 'حلويات ومشروبات' && (t.startsWith('شاي') || t.startsWith('قهوة') || t.startsWith('سحلب') || t.startsWith('كركديه') || t.startsWith('عصير') || t.startsWith('شراب') || t.startsWith('مشروب')));
  if (isActualDrink) {
    return 'drink';
  }

  // 3. Sweets / Desserts
  if (c === 'حلويات ومشروبات' || [
    'كنافة', 'معمول', 'بقلاوة', 'كيك', 'بسبوسة', 'قطايف', 'برازق', 'غريبة',
    'مهلبية', 'هريسة', 'رز بحليب', 'أم علي', 'بلح الشام', 'عوامة', 'لقيمات',
    'مشبك', 'تارت', 'حلاوة الجبن', 'تمرية', 'بين نارين', 'مفروكة', 'كليجة',
    'زنود الست', 'دانغو', 'دوراياكي', 'موتشي', 'براوني', 'تشيز كيك',
    'بانا كوتا', 'كريم كراميل', 'سفوف', 'عصيدة', 'زلابية'
  ].some(w => t.includes(w))) {
    if (t.includes('كنافة')) return 'dessert_knafeh';
    if (t.includes('بسبوسة') || t.includes('هريسة') || t.includes('نمورة') || t.includes('سفوف')) return 'dessert_basbousa';
    if (t.includes('عوامة') || t.includes('لقيمات') || t.includes('مشبك') || t.includes('بلح الشام') || t.includes('زلابية')) return 'dessert_fried';
    if (t.includes('معمول') || t.includes('برازق') || t.includes('غريبة') || t.includes('كليجة') || t.includes('بسكويت') || t.includes('كوكيز')) return 'dessert_cookies';
    if (t.includes('بقلاوة') || t.includes('زنود الست') || t.includes('بين نارين')) return 'dessert_baklava';
    if (t.includes('مهلبية') || t.includes('رز بحليب') || t.includes('حلاوة الجبن') || t.includes('أم علي') || t.includes('بانا كوتا') || t.includes('كريم كراميل')) return 'dessert_pudding';
    return 'dessert_cake';
  }

  // 4. Salads
  if (c === 'مقبلات وسلطات') {
    if (['فتوش', 'تبولة', 'سلطة', 'سيزر', 'كولسلو', 'سلطه', 'جرجير'].some(w => t.includes(w))) return 'salad';
    if (['حمص', 'متبل', 'بابا غنوج', 'لبنة', 'مسبحة'].some(w => t.includes(w))) return 'dip_cold';
    if (['كبة', 'سمبوسك', 'برك', 'فطائر'].some(w => t.includes(w))) return 'hot_appetizer';
  }

  // 5. Soups
  if (c === 'شوربات' || t.includes('شوربة') || t.includes('حساء') || t.includes('حريرة') || t.includes('كشك')) {
    if (t.includes('عدس')) return 'soup_lentil';
    if (t.includes('فريكة')) return 'soup_freekeh';
    if (t.includes('حريرة')) return 'soup_harira';
    return 'soup_general';
  }

  // 6. Breakfast
  if (c === 'فطور وعشاء' || ['فطور', 'عشاء'].some(w => t.includes(w))) {
    if (['بيض', 'شكشوكة', 'عجة', 'أومليت', 'مفركة بيض', 'عيون'].some(w => t.includes(w))) return 'breakfast_egg';
    if (['لبنة', 'جبنة', 'حلوم', 'مقدوس'].some(w => t.includes(w))) return 'breakfast_dairy';
  }

  // 7. Stuffed / Vine Leaves / Mahshi
  if (['محشي', 'يبرق', 'ورق عنب', 'دولمة', 'ملفوف', 'كوسا محشي'].some(w => t.includes(w)) && !t.includes('لبن')) {
    return 'mahshi';
  }

  // 8. Yogurt dishes
  if (['شاكرية', 'كبة لبنية', 'باشا وعساكره', 'لبنية', 'شيخ المحشي باللبن', 'شيخ المحشي كوسا باللبن', 'أذان الشايب'].some(w => t.includes(w))) {
    return 'yogurt_dish';
  }

  // 9. Rice dishes
  if (['كبسة', 'برياني', 'مندي', 'مجبوس', 'بخاري', 'مدفون', 'بايلا', 'ريزوتو', 'زرب'].some(w => t.includes(w))) {
    return 'rice_feast';
  }

  // 10. Pasta
  if (['معكرونة', 'سباغيتي', 'باستا', 'نودلز', 'بيني', 'فيتوتشيني', 'رافيولي'].some(w => t.includes(w))) {
    return 'pasta';
  }

  // 11. Pastries
  if (c === 'معجنات ومخبوزات' || [
    'مناقيش', 'فطائر', 'بيتزا', 'صفيحة', 'بوراك', 'سمبوسك', 'كرواسون', 'خبز',
    'فوكاشيا', 'فطيرة', 'منقوشة', 'لحم بعجين'
  ].some(w => t.includes(w))) {
    return 'pastry';
  }

  // 12. Chicken
  if (['دجاج', 'فراخ', 'شيش طاووق', 'كوردون بلو', 'تندر', 'بروستد', 'مسحب', 'شاورما دجاج'].some(w => t.includes(w))) {
    return 'chicken';
  }

  // 13. Vegetarian stews
  if (['خضار', 'سبانخ', 'بامية', 'فاصولياء', 'لوبياء', 'عدس', 'مجدرة', 'مسقعة', 'مفركة بطاطا', 'مجلجلة'].some(w => t.includes(w)) &&
      !t.includes('لحم') && !t.includes('دجاج') && !t.includes('موزات') && !t.includes('كفتة') && !t.includes('غنم') && !t.includes('عجل') && !t.includes('ريش')) {
    if (t.includes('مجدرة') || t.includes('مجلجلة')) return 'mujadara';
    return 'vegetarian_stew';
  }

  // 14. Meat grills
  if (['كباب', 'كفتة', 'برغر', 'ستيك'].some(w => t.includes(w))) {
    return 'meat_grill';
  }

  // 15. Default: Meat stew
  return 'meat_stew';
}

